// Busca no acervo, configurações de embeddings e aba Relacionados (contra o mock).
import { launch, open, importPdf, report } from './lib.mjs'
import fs from 'node:fs'

const OUT = process.env.MARGEM_SHOTS_BUSCA || '/tmp/busca'
fs.mkdirSync(OUT, { recursive: true })
const results = []
const ok = (name, cond, extra = '') => {
  results.push([name, !!cond])
  console.log(`${cond ? 'OK   ' : 'FALHA'} ${name} ${extra}`)
}
const { browser, page, errors } = await launch()
const shot = (name) => page.screenshot({ path: `${OUT}/${name}.png` })
const calls = (cmd) => page.evaluate((c) => window.__MOCK__.calls.filter((x) => x.cmd === c), cmd)
const modal = page.locator('.search-modal')
const hits = page.locator('.search-modal .hit')
const nDocs = () => page.locator('.doc-item').count()
const settle = (ms = 400) => page.waitForTimeout(ms)
const type = async (text, delay = 25) => {
  await page.locator('.search-modal input').fill('')
  await page.locator('.search-modal input').pressSequentially(text, { delay })
}
const select = async (name) => {
  await page.locator('.doc-select', { hasText: name }).click()
  await settle(500)
}

try {
  await open(page)
  await importPdf(page, 'artigo-2colunas')
  await importPdf(page, 'artigo-1coluna', { wait: false })
  await page.waitForFunction(() => document.querySelectorAll('.doc-item').length === 2, null, { timeout: 60000 })
  await settle(1500)
  ok('2 documentos', (await nDocs()) === 2)

  // ------------------------------------------------------------- abrir e fechar
  await page.getByRole('button', { name: 'Buscar no acervo' }).click()
  await page.waitForSelector('.search-modal input')
  ok('campo da barra lateral abre o painel', await modal.isVisible())
  ok('foco no campo de busca', await page.evaluate(() => document.activeElement?.getAttribute('aria-label') === 'Buscar no acervo' && !!document.activeElement.closest('.search-modal')))
  await shot('00-vazio')
  ok('estado vazio com uma linha', (await modal.locator('.search-note').innerText()).length < 40)
  await page.keyboard.press('Escape')
  await settle(200)
  ok('Esc fecha', (await modal.count()) === 0)
  await page.keyboard.press('Control+Shift+F')
  await settle(250)
  ok('Ctrl+Shift+F abre o painel', await modal.isVisible())
  ok('Ctrl+Shift+F não abriu a busca do documento', (await page.locator('.search-bar').count()) === 0)

  // ------------------------------------------------------------- busca e destaque
  const before = (await calls('search_library')).length
  await type('amostra')
  await page.waitForSelector('.search-modal .hit')
  const sent = (await calls('search_library')).slice(before)
  ok('debounce: uma chamada para a palavra inteira', sent.length === 1, String(sent.length))
  ok('envia a consulta sem filtro', sent[0]?.payload.query === 'amostra' && !sent[0]?.payload.docIds, JSON.stringify(sent[0]?.payload))
  const marks = await modal.locator('mark').allInnerTexts()
  ok('termos destacados com <mark>', marks.length > 0 && marks.every((m) => /amostra/i.test(m)), marks.slice(0, 3).join('|'))
  const groups = await modal.locator('.hit-group').count()
  ok('agrupado por documento (2)', groups === 2, String(groups))
  ok('contagem por documento e total', /\d+ resultados? em 2 documentos/.test(await modal.locator('.search-count').innerText()), await modal.locator('.search-count').innerText())
  ok('modo: palavras', (await modal.locator('.search-mode').innerText()).trim() === 'Palavras')
  await shot('01-resultados')

  // ------------------------------------------------------------- teclado e página certa
  const idBefore = await page.locator('.search-modal input').getAttribute('aria-activedescendant')
  await page.keyboard.press('ArrowDown')
  const idAfter = await page.locator('.search-modal input').getAttribute('aria-activedescendant')
  ok('↓ move o item ativo', idBefore !== idAfter, `${idBefore} -> ${idAfter}`)
  await page.keyboard.press('ArrowUp')
  ok('↑ volta', (await page.locator('.search-modal input').getAttribute('aria-activedescendant')) === idBefore)
  await page.keyboard.press('ArrowDown')
  const active = modal.locator('.hit.active')
  const activePage = (await active.locator('.hit-page').innerText()).replace(/\D/g, '')
  const activeDoc = await active.evaluate((el) => el.closest('.hit-group').querySelector('.hit-doc').textContent)
  await page.keyboard.press('Enter')
  await page.waitForSelector('.source-modal, .modal .pdf-scroll')
  await page.waitForSelector('.pdf-hl', { timeout: 15000 }).catch(() => {})
  await settle(600)
  const gotPage = await page.locator('.page-input').inputValue()
  ok('Enter abre na página do resultado', gotPage === activePage, `${gotPage} vs ${activePage}`)
  ok('documento certo no leitor de fontes', (await page.locator('.modal-head').last().innerText()).includes(activeDoc), activeDoc)
  ok('trecho destacado no PDF', (await page.locator('.pdf-hl').count()) > 0)
  const resolved = await calls('resolve_evidence')
  ok('usa resolve_evidence com o quote', resolved.length > 0 && !!resolved[resolved.length - 1].payload.quote)
  await shot('02-trecho-aberto')
  await page.keyboard.press('Escape')
  await settle(400)
  ok('Esc fecha só o PDF; a busca continua', (await modal.count()) === 1 && (await page.locator('.source-modal').count()) === 0)
  ok('foco volta ao campo', await page.evaluate(() => !!document.activeElement.closest('.search-modal')))
  await hits.nth(0).click()
  await page.waitForSelector('.page-input')
  ok('clique abre o resultado', (await page.locator('.page-input').count()) === 1)
  await page.keyboard.press('Escape')
  await settle(300)

  // ------------------------------------------------------------- sem resultados, erro
  await type('zzxqk')
  await page.waitForSelector('.search-modal .search-note:has-text("Nada encontrado")')
  ok('sem resultados: uma linha', (await modal.locator('.search-note').innerText()) === 'Nada encontrado.')
  await shot('03-sem-resultado')
  await page.evaluate(() => { window.__MOCK__.searchFail = 'Índice indisponível: reinicie o app.' })
  await type('amostra')
  await page.waitForSelector('.search-modal [role=alert]')
  ok('erro com mensagem e Tentar de novo', /Índice indisponível/.test(await modal.locator('[role=alert]').innerText()) && (await modal.getByRole('button', { name: 'Tentar de novo' }).count()) === 1)
  await shot('04-erro')
  await page.evaluate(() => { window.__MOCK__.searchFail = null })
  await modal.getByRole('button', { name: 'Tentar de novo' }).click()
  await page.waitForSelector('.search-modal .hit')
  ok('tentar de novo busca outra vez', (await hits.count()) > 0)

  // ------------------------------------------------------------- respostas antigas
  await page.evaluate(() => { window.__MOCK__.searchDelayMs = 900 })
  await type('variabilidade')
  await settle(500) // a primeira chamada já saiu e demora
  await page.evaluate(() => { window.__MOCK__.searchDelayMs = 20 })
  await type('professores')
  await page.waitForSelector('.search-modal .hit')
  await settle(1300) // a resposta antiga chega agora e deve ser descartada
  const marks2 = await modal.locator('mark').allInnerTexts()
  ok('resposta obsoleta descartada', marks2.length > 0 && marks2.every((m) => /professores/i.test(m)), marks2.slice(0, 3).join('|'))

  // ------------------------------------------------------------- selecionados e renomeado
  await page.keyboard.press('Escape')
  await page.locator('.doc-select').nth(1).dblclick()
  await page.locator('.doc-rename').fill('Segundo artigo renomeado')
  await page.keyboard.press('Enter')
  await settle(300)
  const first = page.locator('.doc-item').nth(0)
  await first.hover()
  await first.locator('input[type=checkbox]').check({ force: true })
  await page.getByRole('button', { name: 'Buscar no acervo' }).click()
  await type('amostra')
  await page.waitForSelector('.search-modal .hit')
  const titles = await modal.locator('.hit-doc').allInnerTexts()
  ok('título renomeado aparece nos resultados', titles.includes('Segundo artigo renomeado'), titles.join('|'))
  await modal.getByRole('button', { name: /Selecionados/ }).click()
  await page.waitForFunction(() => document.querySelectorAll('.search-modal .hit-group').length === 1)
  const lastCall = (await calls('search_library')).pop()
  ok('filtro selecionados envia só os ids selecionados', lastCall.payload.docIds?.length === 1, JSON.stringify(lastCall.payload.docIds))
  ok('um documento só', (await modal.locator('.hit-group').count()) === 1)
  await modal.getByRole('button', { name: 'Todos' }).click()
  await page.waitForFunction(() => document.querySelectorAll('.search-modal .hit-group').length === 2)
  ok('Todos volta aos dois documentos', true)
  await page.keyboard.press('Escape')
  await first.locator('input[type=checkbox]').uncheck({ force: true })

  // ------------------------------------------------------------- indexação em andamento
  await page.getByRole('button', { name: 'Buscar no acervo' }).click()
  await type('amostra')
  await page.waitForSelector('.search-modal .hit')
  await page.evaluate(() => window.__MOCK__.setIndex(12, 40))
  await page.waitForSelector('[data-testid=index-state]')
  ok('rodapé mostra Indexando 12/40', (await page.locator('[data-testid=index-state]').innerText()) === 'Indexando 12/40')
  ok('barra lateral mostra 12/40', (await page.locator('[data-testid=side-index]').innerText()) === '12/40')
  await shot('05-indexando')
  await page.evaluate(() => window.__MOCK__.clearIndex())
  await page.waitForFunction(() => !document.querySelector('[data-testid=index-state]'))
  ok('indicador some ao terminar', (await page.locator('[data-testid=side-index]').count()) === 0)
  await page.keyboard.press('Escape')

  // ------------------------------------------------------------- configurações
  await page.keyboard.press('Control+,')
  await page.waitForSelector('.settings')
  ok('seção Busca por significado (opcional)', await page.getByText('Busca por significado (opcional)').isVisible())
  const urlField = page.getByPlaceholder('http://localhost:11434/v1')
  const modelField = page.getByPlaceholder('nomic-embed-text')
  ok('placeholders do Ollama', (await urlField.count()) === 1 && (await modelField.count()) === 1)
  await urlField.fill('http://localhost:11434/v1')
  await modelField.fill('nomic-embed-text')
  await page.locator('.settings input[type=password]').nth(1).fill('chave-teste')
  await page.getByPlaceholder('voce@universidade.br').fill('gerlan@exemplo.br')
  await shot('06-configuracoes')
  await page.getByRole('button', { name: 'Reindexar' }).click()
  await page.waitForSelector('[data-testid=settings-index]')
  ok('reindexar mostra o progresso', /Indexando \d+\/\d+/.test(await page.locator('[data-testid=settings-index]').innerText()))
  const saved = (await calls('save_settings')).pop()
  ok('configurações enviadas ao backend', saved?.payload.embedBaseUrl === 'http://localhost:11434/v1' && saved.payload.embedModel === 'nomic-embed-text' && saved.payload.embedKey === 'chave-teste' && saved.payload.openalexEmail === 'gerlan@exemplo.br', JSON.stringify(saved?.payload))
  ok('reindex chamado', (await calls('reindex')).length === 1)
  await page.waitForFunction(() => !document.querySelector('[data-testid=settings-index]'), null, { timeout: 8000 })
  await page.getByRole('button', { name: 'Salvar' }).click()
  await settle(300)
  await page.keyboard.press('Control+,')
  await page.waitForSelector('.settings')
  ok('chave guardada: placeholder Manter a atual', (await page.getByPlaceholder('Manter a atual').count()) >= 1)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Buscar no acervo' }).click()
  await type('docentes')
  await page.waitForSelector('.search-modal .hit')
  ok('modo híbrido: palavras + significado', (await modal.locator('.search-mode').innerText()).trim() === 'Palavras + significado')
  ok('híbrido acha sinônimo (docentes ~ professores)', (await hits.count()) > 0)
  await page.keyboard.press('Escape')

  // ------------------------------------------------------------- Relacionados: DOI
  await page.getByRole('tab', { name: 'Relacionados' }).click()
  await select('artigo-2colunas')
  await page.waitForSelector('.rel-card')
  ok('lookup por DOI: trabalho identificado', /Letramento estatístico de professores/.test(await page.locator('.rel-card h4').innerText()))
  ok('selo por DOI', (await page.locator('.rel-card .tag.src').innerText()).includes('por DOI'))
  const cardText = await page.locator('.rel-card').innerText()
  ok('card com ano, periódico, citações e DOI', /2021/.test(cardText) && /Educação Matemática Pesquisa/.test(cardText) && /128 citações/.test(cardText) && /10\.5555\/mock\.letramento/.test(cardText))
  await page.waitForSelector('.rel-item')
  ok('lista de relacionados (10)', (await page.locator('#rel-panel .rel-item').count()) === 10)
  const item0 = page.locator('#rel-panel .rel-item').first()
  ok('autores: no máximo 3 + et al.', (await page.locator('.rel-authors').allInnerTexts()).every((t) => t.split(',').length <= 3 || /et al\.$/.test(t)) && (await page.locator('.rel-authors', { hasText: 'et al.' }).count()) > 0)
  ok('selo Acesso aberto', (await page.locator('#rel-panel .tag.oa').count()) > 0)
  await shot('07-relacionados')
  // abrir no navegador
  const firstUrl = await item0.locator('.rel-title').evaluate((el) => el.textContent)
  await item0.locator('.rel-title').click()
  await settle(200)
  ok('abre no navegador (opener)', /openalex\.org\/W/.test(await page.evaluate(() => window.__MOCK__.opened || '')), firstUrl.slice(0, 30))
  // copiar referência e DOI
  await item0.getByRole('button', { name: /Copiar referência/ }).click()
  await settle(200)
  const ref = await page.evaluate(() => navigator.clipboard.readText())
  ok('copiar referência (ABNT)', /^[A-ZÀ-Ý]+, .+\. .+\. .*\d{4}\./.test(ref) && /Disponível em: https:\/\/doi\.org\//.test(ref), ref.slice(0, 90))
  const doiBtn = item0.getByRole('button', { name: /Copiar DOI/ })
  if (await doiBtn.count()) {
    await doiBtn.click()
    await settle(200)
    ok('copiar DOI', /^10\.5555\/mock\./.test(await page.evaluate(() => navigator.clipboard.readText())))
  }
  // abas internas por teclado
  await page.locator('#rel-tab-related').focus()
  await page.keyboard.press('ArrowRight')
  await page.waitForSelector('#rel-tab-references[aria-selected=true]')
  ok('→ troca de aba interna', true)
  await page.waitForSelector('#rel-panel .rel-item')
  const refsTotal = await page.locator('#rel-tab-references .rel-total').innerText()
  ok('Referências: total conhecido', refsTotal === '37', refsTotal)
  // paginação
  await page.getByRole('button', { name: /Carregar mais/ }).click()
  await page.waitForFunction(() => document.querySelectorAll('#rel-panel .rel-item').length === 20)
  await page.getByRole('button', { name: /Carregar mais/ }).click()
  await page.waitForFunction(() => document.querySelectorAll('#rel-panel .rel-item').length === 30)
  await page.getByRole('button', { name: /Carregar mais/ }).click()
  await page.waitForFunction(() => document.querySelectorAll('#rel-panel .rel-item').length === 37)
  ok('paginação até o fim (37)', (await page.getByRole('button', { name: /Carregar mais/ }).count()) === 0)
  const keys = await page.locator('#rel-panel .rel-title').allInnerTexts()
  ok('sem itens repetidos entre páginas', new Set(keys).size === keys.length)
  await page.locator('#rel-tab-related').click()
  await page.waitForSelector('#rel-panel .rel-item')
  ok('voltar à aba mostra o cache (10 itens)', (await page.locator('#rel-panel .rel-item').count()) === 10)

  // baixar e adicionar
  const dlBtn = page.locator('#rel-panel .rel-item').filter({ has: page.getByRole('button', { name: /Baixar e adicionar/ }) })
  ok('há itens com Baixar e adicionar', (await dlBtn.count()) > 0)
  ok('item sem PDF direto oferece Abrir página', (await page.getByRole('button', { name: 'Abrir página' }).count()) > 0)
  const docsBefore = await nDocs()
  const currentTitle = await page.locator('.related .chat-head p').innerText()
  const itemOf = (title) => page.locator('#rel-panel .rel-item').filter({ has: page.locator('.rel-title', { hasText: title }) })
  const targetTitle = await dlBtn.first().locator('.rel-title').innerText()
  const target = itemOf(targetTitle)
  await page.evaluate(() => { window.__MOCK__.openalex.downloadDelayMs = 900 })
  await target.getByRole('button', { name: /Baixar e adicionar/ }).click()
  ok('mostra progresso (Baixando…)', await target.getByText('Baixando…').isVisible())
  await page.waitForFunction((n) => document.querySelectorAll('.doc-item').length === n + 1, docsBefore, { timeout: 60000 })
  await settle(800)
  ok('documento adicionado à biblioteca', (await nDocs()) === docsBefore + 1)
  ok('não troca o documento aberto', (await page.locator('.related .chat-head p').innerText()) === currentTitle)
  ok('item vira Na biblioteca', (await target.getByRole('button', { name: 'Na biblioteca' }).count()) === 1, targetTitle.slice(0, 30))
  ok('download usou a URL do PDF', /\.pdf$/.test((await calls('download_pdf')).pop().payload.url))
  // erro de download
  await page.evaluate(() => { window.__MOCK__.openalex.downloadFail = 'Não foi possível baixar o PDF: o servidor respondeu 403 (acesso negado).' })
  const target2Title = await dlBtn.first().locator('.rel-title').innerText()
  const target2 = itemOf(target2Title)
  await target2.getByRole('button', { name: /Baixar e adicionar/ }).click()
  await target2.locator('[role=alert]').waitFor()
  ok('erro de download claro', /403/.test(await target2.locator('[role=alert]').innerText()))
  ok('botão volta a funcionar após o erro', await target2.getByRole('button', { name: /Baixar e adicionar/ }).isEnabled())
  await page.evaluate(() => { window.__MOCK__.openalex.downloadFail = null })
  await shot('07b-relacionados-erro-download')

  // erro de rede e tentar de novo na lista
  await page.evaluate(() => { window.__MOCK__.openalex.relatedFail = 1 })
  await page.locator('#rel-tab-cited_by').click()
  await page.waitForSelector('#rel-panel [role=alert]')
  ok('erro de rede na lista', /OpenAlex/.test(await page.locator('#rel-panel [role=alert]').innerText()))
  await page.locator('#rel-panel').getByRole('button', { name: 'Tentar de novo' }).click()
  await page.waitForSelector('#rel-panel .rel-item')
  ok('tentar de novo carrega a lista (Citado por)', (await page.locator('#rel-tab-cited_by .rel-total').innerText()) === '52')

  // já na biblioteca por título normalizado + abrir na biblioteca
  const someTitle = await page.locator('#rel-panel .rel-item .rel-title').nth(3).innerText()
  await page.locator('.doc-item').last().hover()
  await page.locator('.doc-item').last().locator('.doc-select').dblclick()
  await page.locator('.doc-rename').fill(someTitle.toUpperCase())
  await page.keyboard.press('Enter')
  await settle(500)
  await select('artigo-2colunas')
  await page.waitForSelector('#rel-panel .rel-item')
  ok('título normalizado marca "Na biblioteca"', (await page.locator('#rel-panel .rel-item').nth(3).getByRole('button', { name: 'Na biblioteca' }).count()) === 1)

  // ------------------------------------------------------------- Relacionados: título com candidatos
  await select('Segundo artigo renomeado')
  await page.waitForSelector('.rel-chooser .rel-item')
  const cand = await page.locator('.rel-chooser .rel-item').count()
  ok('por título: lista de candidatos', cand === 3, String(cand))
  ok('sem abas internas antes de escolher', (await page.locator('.rel-tabs').count()) === 0)
  await shot('08-candidatos')
  await page.locator('.rel-chooser .rel-item').nth(1).getByRole('button', { name: 'Escolher' }).click()
  await page.waitForSelector('.rel-card')
  ok('escolher vincula (selo vinculado)', (await page.locator('.rel-card .tag.src').innerText()).includes('vinculado'))
  ok('openalex_link com o trabalho', (await calls('openalex_link')).some((c) => /W1003$/.test(c.payload.workId || '')))
  await page.waitForSelector('#rel-panel .rel-item')
  // trocar por busca manual (DOI)
  await page.getByRole('button', { name: 'Trocar' }).click()
  await page.getByLabel('Buscar no OpenAlex').fill('10.5555/mock.1002')
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await page.waitForSelector('.rel-chooser .rel-item')
  ok('busca manual por DOI acha 1 candidato', (await page.locator('.rel-chooser .rel-item').count()) === 1)
  await shot('09-manual')
  await page.locator('.rel-chooser .rel-item').getByRole('button', { name: 'Escolher' }).click()
  await page.waitForFunction(() => /Variabilidade e amostragem no ensino médio/.test(document.querySelector('.rel-card h4')?.textContent || ''))
  ok('trocar: novo trabalho vinculado', true)
  // desvincular
  await page.getByRole('button', { name: 'Desvincular' }).click()
  await page.waitForSelector('.rel-chooser .search-note')
  ok('desvincular limpa o vínculo', (await calls('openalex_link')).pop().payload.workId === null && (await page.locator('.rel-card').count()) === 0)

  // ------------------------------------------------------------- Relacionados: erro no lookup e retry
  await page.evaluate(() => { window.__MOCK__.openalex.lookupFail = 'Não foi possível falar com o OpenAlex: sem conexão.' })
  await importPdf(page, 'uma-pagina', { wait: false })
  await page.waitForSelector('.rel-ident [role=alert]')
  ok('erro no lookup', /sem conexão/.test(await page.locator('.rel-ident [role=alert]').innerText()))
  await page.evaluate(() => { window.__MOCK__.openalex.lookupFail = null })
  await page.locator('.rel-ident').getByRole('button', { name: 'Tentar de novo' }).click()
  await page.waitForSelector('.rel-chooser')
  ok('tentar de novo no lookup', /Não identificado/.test(await page.locator('.rel-chooser').innerText()))
  await shot('10-nao-identificado')
  await select('artigo-2colunas')
  await page.waitForSelector('.rel-card')
  ok('cache: voltar ao documento mostra o trabalho sem nova espera', (await page.locator('.rel-card').count()) === 1)
} catch (e) {
  console.log('ERRO', e.message)
  await shot('erro').catch(() => {})
  results.push(['sem exceção', false])
}
report(errors)
console.log(`${results.filter((r) => r[1]).length}/${results.length} ok`)
await browser.close()
process.exit(results.every((r) => r[1]) ? 0 : 1)
